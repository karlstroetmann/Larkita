"""A minimal tree class.  It is only used internally, to represent parsed grammar files;
the parsers generated by Larkita return nested tuples."""

from copy import deepcopy
from typing import List, Callable, Iterator, Any


class Tree:
    """Stores "data" (the name of a rule) and "children" (the matched sub-rules and terminals)."""

    data: str
    children: List[Any]

    def __init__(self, data: str, children: List[Any]) -> None:
        self.data = data
        self.children = children

    def __repr__(self):
        return 'Tree(%r, %r)' % (self.data, self.children)

    def _pretty(self, level, indent_str):
        yield f'{indent_str*level}{self.data}'
        if len(self.children) == 1 and not isinstance(self.children[0], Tree):
            yield f'\t{self.children[0]}\n'
        else:
            yield '\n'
            for n in self.children:
                if isinstance(n, Tree):
                    yield from n._pretty(level+1, indent_str)
                else:
                    yield f'{indent_str*(level+1)}{n}\n'

    def pretty(self, indent_str: str='  ') -> str:
        """Returns an indented string representation of the tree."""
        return ''.join(self._pretty(0, indent_str))

    def __eq__(self, other):
        try:
            return self.data == other.data and self.children == other.children
        except AttributeError:
            return False

    def __ne__(self, other):
        return not (self == other)

    def __hash__(self) -> int:
        return hash((self.data, tuple(self.children)))

    def iter_subtrees(self) -> 'Iterator[Tree]':
        """Depth-first iteration, bottom-up.

        Iterates over all the subtrees, never returning to the same node twice.
        """
        queue = [self]
        subtrees = dict()
        for subtree in queue:
            subtrees[id(subtree)] = subtree
            queue += [c for c in reversed(subtree.children)
                      if isinstance(c, Tree) and id(c) not in subtrees]

        del queue
        return reversed(list(subtrees.values()))

    def iter_subtrees_topdown(self) -> 'Iterator[Tree]':
        """Breadth-first iteration.

        Iterates over all the subtrees, return nodes in order like pretty() does.
        """
        stack = [self]
        while stack:
            node = stack.pop()
            if not isinstance(node, Tree):
                continue
            yield node
            for child in reversed(node.children):
                stack.append(child)

    def find_pred(self, pred: 'Callable[[Tree], bool]') -> 'Iterator[Tree]':
        """Returns all nodes of the tree that evaluate pred(node) as true."""
        return filter(pred, self.iter_subtrees())

    def find_data(self, data: str) -> 'Iterator[Tree]':
        """Returns all nodes of the tree whose data equals the given data."""
        return self.find_pred(lambda t: t.data == data)

    def expand_kids_by_data(self, *data_values):
        """Expand (inline) children with any of the given data values. Returns True if anything changed"""
        changed = False
        for i in range(len(self.children)-1, -1, -1):
            child = self.children[i]
            if isinstance(child, Tree) and child.data in data_values:
                self.children[i:i+1] = child.children
                changed = True
        return changed

    def scan_values(self, pred: 'Callable[[Any], bool]') -> Iterator[Any]:
        """Return all values in the tree that evaluate pred(value) as true."""
        for c in self.children:
            if isinstance(c, Tree):
                for t in c.scan_values(pred):
                    yield t
            else:
                if pred(c):
                    yield c

    def __deepcopy__(self, memo):
        return type(self)(self.data, deepcopy(self.children, memo))

    def copy(self) -> 'Tree':
        return type(self)(self.data, self.children)


class SlottedTree(Tree):
    __slots__ = 'data', 'children'
